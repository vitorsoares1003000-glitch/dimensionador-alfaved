# ==========================================
# FUNÇÕES AUXILIARES
# ==========================================

def obter_modelos_por_tipo(tipo):
    """Retorna lista de modelos do tipo especificado (gaxetado/semi-soldado)"""
    return {k: v for k, v in BANCO_MODELOS.items() if v.get("tipo") == tipo}

def obter_modelos_por_serie(serie):
    """Retorna lista de modelos da série especificada"""
    return {k: v for k, v in BANCO_MODELOS.items() if v.get("serie") == serie}

def obter_modelos_por_temp_max(temp_minima):
    """Retorna modelos que suportam a temperatura mínima especificada"""
    return {k: v for k, v in BANCO_MODELOS.items() if v.get("temp_max", 0) >= temp_minima}

def obter_modelos_por_pressao(pressao_minima):
    """Retorna modelos que suportam a pressão mínima especificada"""
    return {k: v for k, v in BANCO_MODELOS.items() if v.get("pressao_max", 0) >= pressao_minima}

def validar_compatibilidade_gaxeta(modelo_nome, temp_operacao):
    """Recomenda gaxetas compatíveis para um modelo e temperatura"""
    modelo = BANCO_MODELOS.get(modelo_nome)
    if not modelo:
        return None
    
    gaxetas_recomendadas = []
    for gaxeta_nome in modelo.get("gaxetas_disponiveis", []):
        gaxeta = BANCO_GAXETAS.get(gaxeta_nome)
        if gaxeta and gaxeta["temp_min"] <= temp_operacao <= gaxeta["temp_max"]:
            gaxetas_recomendadas.append(gaxeta_nome)
    
    return gaxetas_recomendadas if gaxetas_recomendadas else None

def filtrar_modelos(tipo=None, serie=None, pressao_min=None, temp_max_min=None):
    """Filtra modelos por múltiplos critérios"""
    resultado = BANCO_MODELOS.copy()
    
    if tipo:
        resultado = {k: v for k, v in resultado.items() if v.get("tipo") == tipo}
    if serie:
        resultado = {k: v for k, v in resultado.items() if v.get("serie") == serie}
    if pressao_min:
        resultado = {k: v for k, v in resultado.items() if v.get("pressao_max", 0) >= pressao_min}
    if temp_max_min:
        resultado = {k: v for k, v in resultado.items() if v.get("temp_max", 0) >= temp_max_min}
    
    return resultado
